"""
Iteration 2 regression tests - new features:
- Line detail exposes nationalMinutes / smsUsed / cdrs.calledNumber
- /api/me/summary lines include nationalMinutes / smsUsed
- Invoices have period/dueDate/customerAddress/paymentMethod/consumption
- PDF generated with Goroky layout
- POST /api/customers accepts iban/paymentMethod; POST /api/orders reflects them
"""
import os
import uuid
import requests
import pytest

BASE_URL = os.environ.get("REACT_APP_BACKEND_URL", "https://likes-telecom-app.preview.emergentagent.com").rstrip("/")
ADMIN_EMAIL = "admin@goroky.com"
ADMIN_PASS = "Goroky2026!"
CLIENT_EMAIL = "cliente@goroky.com"
CLIENT_PASS = "Cliente2026!"


def _login(email, pw):
    r = requests.post(f"{BASE_URL}/api/auth/login", json={"email": email, "password": pw}, timeout=20)
    assert r.status_code == 200, f"login failed {email}: {r.status_code} {r.text}"
    return r.json()["token"]


@pytest.fixture(scope="module")
def admin_token():
    return _login(ADMIN_EMAIL, ADMIN_PASS)


@pytest.fixture(scope="module")
def client_token():
    return _login(CLIENT_EMAIL, CLIENT_PASS)


def _h(t):
    return {"Authorization": f"Bearer {t}"}


# ---------- LINE DETAIL: nationalMinutes / smsUsed / cdrs ----------
class TestLineDetailUsage:
    def test_mobile_line_has_usage_fields(self, admin_token):
        # find a Mobile ACTIVE line
        lines = requests.get(f"{BASE_URL}/api/lines", headers=_h(admin_token), timeout=20).json()
        mobile = next((l for l in lines if l.get("family") == "Mobile"), None)
        assert mobile is not None, "no mobile line in seeded data"
        r = requests.get(f"{BASE_URL}/api/lines/{mobile['lineNumber']}", headers=_h(admin_token), timeout=20)
        assert r.status_code == 200, r.text
        d = r.json()
        for k in ["nationalMinutes", "smsUsed", "usedGB", "totalGB", "cdrs"]:
            assert k in d, f"missing field {k} in line detail"
        assert isinstance(d["nationalMinutes"], int)
        assert isinstance(d["smsUsed"], int)
        assert isinstance(d["cdrs"], list)
        assert len(d["cdrs"]) > 0, "expected cdrs generated by seed"

    def test_cdrs_contain_voice_sms_data_and_calledNumber(self, admin_token):
        lines = requests.get(f"{BASE_URL}/api/lines", headers=_h(admin_token), timeout=20).json()
        mobile = next((l for l in lines if l.get("family") == "Mobile"), None)
        d = requests.get(f"{BASE_URL}/api/lines/{mobile['lineNumber']}", headers=_h(admin_token), timeout=20).json()
        cdrs = d["cdrs"]
        types = {c.get("type") for c in cdrs}
        # At least VOICE should be present (main check); SMS/DATA may vary due to random.
        assert "VOICE" in types, f"expected VOICE cdr, got {types}"
        # every VOICE cdr has calledNumber, date and duration
        for c in cdrs:
            assert "date" in c and c["date"]
            assert "duration" in c
            if c["type"] in ("VOICE", "SMS"):
                assert c.get("calledNumber"), f"VOICE/SMS cdr missing calledNumber: {c}"


