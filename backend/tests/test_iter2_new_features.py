# ---------- INVOICE FIELDS + PDF ----------
class TestInvoiceGorokyFormat:
    def test_invoice_has_new_fields(self, admin_token):
        invs = requests.get(f"{BASE_URL}/api/invoices", headers=_h(admin_token), timeout=20).json()
        assert invs, "expected seeded invoices"
        inv = invs[0]
        for k in ["period", "dueDate", "customerAddress", "paymentMethod", "consumption"]:
            assert k in inv, f"invoice missing {k}: keys={list(inv.keys())}"
        assert isinstance(inv["consumption"], list)

    def test_pdf_is_valid_goroky(self, admin_token):
        invs = requests.get(f"{BASE_URL}/api/invoices", headers=_h(admin_token), timeout=20).json()
        inv = invs[0]
        r = requests.get(f"{BASE_URL}/api/invoices/{inv['id']}/pdf", headers=_h(admin_token), timeout=30)
        assert r.status_code == 200
        assert r.headers.get("content-type", "").startswith("application/pdf")
        assert r.content[:4] == b"%PDF"
        # at least 2 pages -> reasonable size
        assert len(r.content) > 2000, f"pdf suspiciously small: {len(r.content)}"

    def test_pdf_client_own(self, client_token):
        invs = requests.get(f"{BASE_URL}/api/invoices", headers=_h(client_token), timeout=20).json()
        assert invs
        inv = invs[0]
        r = requests.get(f"{BASE_URL}/api/invoices/{inv['id']}/pdf", headers=_h(client_token), timeout=30)
        assert r.status_code == 200
        assert r.content[:4] == b"%PDF"


# ---------- CUSTOMER iban/paymentMethod + ORDER carries paymentMethod ----------
class TestCustomerPaymentAndOrderPropagation:
    def test_create_customer_with_iban_and_payment(self, admin_token):
        unique_id = f"T{uuid.uuid4().hex[:8].upper()}"
        payload = {
            "fiscalId": unique_id,
            "customerType": "Residential",
            "name": "TEST_IbanCli",
            "firstSurname": "Prueba",
            "email": f"test_{unique_id.lower()}@qa.com",
            "contactPhone": "600000000",
            "iban": "ES9121000418450200051332",
            "paymentMethod": "SEPA CORE",
            "street": "Calle Test",
            "streetNumber": "5",
            "postalCode": "28080",
            "cityName": "Madrid",
            "provinceName": "Madrid",
        }
        r = requests.post(f"{BASE_URL}/api/customers", headers=_h(admin_token), json=payload, timeout=20)
        assert r.status_code == 200, r.text
        c = r.json()
        assert c["iban"] == payload["iban"]
        assert c["paymentMethod"] == "SEPA CORE"

        # persistence check via GET
        r2 = requests.get(f"{BASE_URL}/api/customers/{unique_id}", headers=_h(admin_token), timeout=20)
        assert r2.status_code == 200
        cust = r2.json()["customer"]
        assert cust["iban"] == payload["iban"]
        assert cust["paymentMethod"] == "SEPA CORE"

        # place order for this customer
        prods = requests.get(f"{BASE_URL}/api/products?family=Mobile", headers=_h(admin_token), timeout=20).json()
        pid = prods[0]["productId"]
        ro = requests.post(f"{BASE_URL}/api/orders", headers=_h(admin_token),
                           json={"fiscalId": unique_id, "productId": pid}, timeout=20)
        assert ro.status_code == 200, ro.text
        inv_id = ro.json()["invoiceId"]

        # verify invoice reflects paymentMethod + consumption listing includes the new mobile line
        invs = requests.get(f"{BASE_URL}/api/invoices?fiscalId={unique_id}",
                            headers=_h(admin_token), timeout=20).json()
        assert invs, "expected invoice after order"
        inv = next(i for i in invs if i["id"] == inv_id)
        assert inv["paymentMethod"] == "SEPA CORE"
        assert isinstance(inv["consumption"], list)
        # Consumption must contain the newly created mobile line
        line_numbers = [c.get("lineNumber") for c in inv["consumption"]]
        assert len(line_numbers) >= 1, f"expected mobile line in consumption, got {inv['consumption']}"

        # PDF valid too
        pdf = requests.get(f"{BASE_URL}/api/invoices/{inv_id}/pdf", headers=_h(admin_token), timeout=30)
        assert pdf.status_code == 200
        assert pdf.content[:4] == b"%PDF"
